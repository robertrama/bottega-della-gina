  function applyLanguage(lang) {
    var dict = DICT[lang] || DICT.it;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    var page = document.body.getAttribute('data-i18n-page');
    var titleKey = page && dict[page + '_meta_title'] ? page + '_meta_title' : 'meta_title';
    var descKey = page && dict[page + '_meta_description'] ? page + '_meta_description' : 'meta_description';
    document.title = dict[titleKey];
    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', dict[descKey]);

    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang-btn') === lang);
    });

    try { localStorage.setItem('bdg-lang', lang); } catch (e) { /* storage unavailable */ }
    window.__bdgLang = lang;
  }

  function initLang() {
    var saved;
    try { saved = localStorage.getItem('bdg-lang'); } catch (e) { saved = null; }
    var lang = saved || 'it';
    applyLanguage(lang);

    var toggle = document.getElementById('lang-toggle');
    if (toggle) {
      toggle.addEventListener('click', function () {
        var current = window.__bdgLang || 'it';
        applyLanguage(current === 'it' ? 'en' : 'it');
      });
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLang);
  } else {
    initLang();
  }

